function shuffle(items) {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

function getSource(tab) {
  return tab === "general" ? questions : questions.filter((q) => q.category === tab);
}

function ensureTab(tab) {
  if (!state.current[tab]) {
    state.attempts[tab] = 0;
    state.score[tab] = 0;
    state.current[tab] = pickQuestion(tab);
  }
}

function pickQuestion(tab) {
  const source = getSource(tab);
  if (source.length === 1) return source[0];
  let next = source[Math.floor(Math.random() * source.length)];
  while (state.current[tab] && next === state.current[tab]) {
    next = source[Math.floor(Math.random() * source.length)];
  }
  return next;
}

function render() {
  if (state.tab === "bank") {
    renderBank();
    return;
  }

  quizCard.hidden = false;
  bankCard.hidden = true;
  statLabels[1].textContent = "Верно";
  statLabels[2].textContent = "Попытка";
  ensureTab(state.tab);
  const q = state.current[state.tab];
  const attempts = state.attempts[state.tab];

  sectionName.textContent = sectionTitles[state.tab];
  scoreText.textContent = `${state.score[state.tab]}/${attempts}`;
  counterText.textContent = attempts === 0 ? "1" : String(attempts + 1);
  topicLabel.textContent = q.topic;
  questionType.textContent = q.type === "admin" ? "ФИО + зона" : "Выбор ответа";
  questionText.textContent = q.text;
  resultBox.hidden = true;
  resultBox.className = "result";
  resultBox.textContent = "";
  nextBtn.hidden = true;
  checkBtn.hidden = false;
  checkBtn.disabled = false;
  answerForm.innerHTML = "";

  if (q.type === "admin") {
    renderAdminQuestion(q);
  } else {
    renderChoiceQuestion(q);
  }
}

function renderChoiceQuestion(q) {
  const displayOptions = shuffle(q.options.map((option, index) => ({ option, index })));
  displayOptions.forEach(({ option, index }) => {
    const label = document.createElement("label");
    label.className = "option";
    const displayText = normalizeOptionText(option, index === q.answer);
    label.innerHTML = `
      <input type="radio" name="answer" value="${index}">
      <span>${displayText}</span>
    `;
    answerForm.append(label);
  });
}

function normalizeOptionText(option, isCorrect) {
  if (isCorrect) return option;
  return option
    .replace(/^Только\s+/i, "")
    .replace(/^Только\s+/i, "");
}

function renderAdminQuestion(q) {
  const correct = adminPeople[q.personIndex];
  const nameOptions = makeAdminOptions(q.personIndex, "name");
  const roleOptions = makeAdminOptions(q.personIndex, "role");
  const photo = document.createElement("img");
  photo.className = "admin-photo";
  photo.src = correct.photo;
  photo.alt = "Фото представителя администрации";
  answerForm.append(photo);
  answerForm.append(createSelectGroup("fio", "1. ФИО", nameOptions, correct.name));
  answerForm.append(createSelectGroup("role", "2. Чем занимается", roleOptions, correct.role));
}

function makeAdminOptions(correctIndex, field) {
  const others = adminPeople
    .map((person, index) => ({ person, index }))
    .filter((item) => item.index !== correctIndex);
  return shuffle([adminPeople[correctIndex], ...shuffle(others).slice(0, 3).map((item) => item.person)])
    .map((person) => person[field]);
}

function createSelectGroup(name, labelText, options) {
  const wrap = document.createElement("div");
  wrap.className = "match-group";
  const label = document.createElement("label");
  label.setAttribute("for", name);
  label.textContent = labelText;
  const select = document.createElement("select");
  select.name = name;
  select.id = name;
  select.innerHTML = `<option value="">Выберите вариант</option>` + options.map((item) => `<option value="${escapeHtml(item)}">${item}</option>`).join("");
  wrap.append(label, select);
  return wrap;
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

function checkAnswer() {
  const q = state.current[state.tab];
  let isCorrect = false;
  let explanation = q.explanation;

  if (q.type === "admin") {
    const correct = adminPeople[q.personIndex];
    const selectedName = answerForm.elements.fio.value;
    const selectedRole = answerForm.elements.role.value;
    if (!selectedName || !selectedRole) {
      showMessage("Нужно выбрать оба пункта: ФИО и зону ответственности.", false, true);
      return;
    }
    isCorrect = selectedName === correct.name && selectedRole === correct.role;
    explanation = `<strong>${correct.name}</strong>${correct.role}`;
  } else {
    const checked = answerForm.querySelector("input[name='answer']:checked");
    if (!checked) {
      showMessage("Выберите один вариант ответа.", false, true);
      return;
    }
    isCorrect = Number(checked.value) === q.answer;
  }

  state.attempts[state.tab] += 1;
  if (isCorrect) state.score[state.tab] += 1;

  if (isCorrect) {
    showMessage(`<strong>Верно</strong>${explanation || getCorrectAnswerText(q)}`, true);
  } else {
    showMessage(`<strong>Неверно</strong>${explanation}`, false);
  }

  checkBtn.hidden = true;
  nextBtn.hidden = false;
  setFormDisabled(true);
  updateStatsAfterCheck();
}

function showMessage(message, isGood, temporary = false) {
  resultBox.hidden = false;
  resultBox.className = `result ${isGood ? "is-good" : "is-bad"}`;
  resultBox.innerHTML = message;
  if (temporary) {
    resultBox.classList.remove("is-bad");
    resultBox.style.background = "#fff7ed";
    resultBox.style.color = "#9a3412";
  } else {
    resultBox.removeAttribute("style");
  }
}

function setFormDisabled(disabled) {
  answerForm.querySelectorAll("input, select").forEach((control) => {
    control.disabled = disabled;
  });
}

function updateStatsAfterCheck() {
  scoreText.textContent = `${state.score[state.tab]}/${state.attempts[state.tab]}`;
  counterText.textContent = String(state.attempts[state.tab] + 1);
}

function nextQuestion() {
  state.current[state.tab] = pickQuestion(state.tab);
  render();
}

function resetAll() {
  state.current = {};
  state.attempts = {};
  state.score = {};
  render();
}

tabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    tabs.forEach((item) => item.classList.toggle("is-active", item === tab));
    state.tab = tab.dataset.tab;
    render();
  });
});

bankFilter.addEventListener("change", renderBank);
checkBtn.addEventListener("click", checkAnswer);
nextBtn.addEventListener("click", nextQuestion);
resetBtn.addEventListener("click", resetAll);
render();

function getCorrectAnswerText(q) {
  if (q.type === "admin") {
    const person = adminPeople[q.personIndex];
    return `${person.name}. ${person.role}`;
  }
  return `Правильный ответ: ${q.options[q.answer]}.`;
}

function getBankItems() {
  return questions.map((q, index) => ({ ...q, bankIndex: index + 1 }));
}

function renderBank() {
  const filter = bankFilter.value;
  const allItems = getBankItems();
  const items = filter === "all" ? allItems : allItems.filter((q) => q.category === filter);

  quizCard.hidden = true;
  bankCard.hidden = false;
  statLabels[1].textContent = "Всего";
  statLabels[2].textContent = "Показано";
  sectionName.textContent = "Банк вопросов";
  scoreText.textContent = `${allItems.length}`;
  counterText.textContent = `${items.length}`;
  bankCount.textContent = `Показано: ${items.length} из ${allItems.length}`;
  bankList.innerHTML = "";

  items.forEach((q) => {
    const item = document.createElement("details");
    item.className = "bank-item";
    const answer = q.type === "admin"
      ? getCorrectAnswerText(q)
      : `${q.options[q.answer]}. ${q.explanation || ""}`;
    item.innerHTML = `
      <summary>
        <span class="bank-meta">${q.bankIndex}. ${getCategoryTitle(q.category)} / ${q.topic}</span>
        <span>${q.text}</span>
      </summary>
      <div class="bank-answer"><strong>Ответ:</strong> ${escapeHtml(answer)}</div>
    `;
    bankList.append(item);
  });
}

function getCategoryTitle(category) {
  if (category === "generalOnly") return "Общее";
  return sectionTitles[category] || "Общее";
}
