function createDeepQuestions(facts) {
  const selectedFacts = selectDeepFacts(facts);
  const existingTexts = new Set(questions.map((q) => q.text));
  const textQuestions = selectedFacts.map((fact) => {
    const explanation = fact.h || fact.a;
    return {
      category: fact.c,
      topic: fact.t,
      type: "text",
      text: makeTextQuestionText(fact, existingTexts),
      answerText: fact.a,
      explanation,
    };
  });
  const choiceQuestions = selectedFacts.map((fact) => {
    const explanation = fact.h || fact.a;
    return {
      category: fact.c,
      topic: fact.t,
      text: makeChoiceQuestionText(fact),
      options: buildFactOptions(fact, facts),
      answer: 0,
      explanation: `${fact.a} ${explanation}`,
    };
  });
  return [...textQuestions, ...choiceQuestions];
}

function makeTextQuestionText(fact, existingTexts) {
  if (existingTexts.has(fact.q)) {
    return `Ответьте без вариантов: ${fact.q}`;
  }
  return fact.q;
}

function makeChoiceQuestionText(fact) {
  return `Выберите верный ответ по вопросу: ${fact.q}`;
}

function selectDeepFacts(facts) {
  const quotas = {
    history: 25,
    generalOnly: 35,
    student: 33,
    docs: 37,
  };
  return Object.entries(quotas).flatMap(([category, limit]) =>
    facts.filter((fact) => fact.c === category).slice(0, limit),
  );
}

function buildFactOptions(fact, facts) {
  const local = facts
    .filter((item) => item !== fact && item.c === fact.c && item.t === fact.t)
    .map((item) => item.a);
  const related = facts
    .filter((item) => item !== fact && item.c === fact.c)
    .map((item) => item.a);
  const global = facts
    .filter((item) => item !== fact)
    .map((item) => item.a);
  return [fact.a, ...uniqueOptions([...local, ...related, ...global], fact.a).slice(0, 3)];
}

function uniqueOptions(options, answer) {
  const seen = new Set([answer]);
  return options.filter((option) => {
    const key = option.toLowerCase();
    if (seen.has(key) || option.length > 180) return false;
    seen.add(key);
    return true;
  });
}

